#!/usr/bin/env python3
"""Render references/platform-specs.md from data/platform-specs.json.

The JSON is the single source of truth. The markdown exists so a human (or an
agent that wants prose) can read the same facts, and it is regenerated, never
hand-edited. CI fails if the two drift (see tests/test_repo.py).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "data" / "platform-specs.json"
OUT = ROOT / "references" / "platform-specs.md"

KIND_TITLES = {
    "hard": "Hard limits (platform enforces these; the validator fails on them)",
    "policy": "Official rules (can change; the validator warns)",
    "algorithm": "Ranking signals (official where published, otherwise directional)",
    "heuristic": "Craft guidance (no official source; never present as a platform rule)",
}
SOURCE_LABEL = {
    "primary": "official",
    "primary-code": "official code",
    "primary-mirror": "official, via mirror",
    "primary-quoted": "official, quoted",
    "secondary": "secondary",
    "none": "none",
}


def fmt(value: object) -> str:
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def render(data: dict) -> str:
    lines = [
        "# Platform specifications",
        "",
        f"Data version `{data['data_version']}`, generated from `data/platform-specs.json`. Do not edit this file by hand.",
        "",
        "Read this before writing for a platform. Every fact carries a kind, a verification date and a source type. "
        "Only `hard` and `policy` facts may be stated to the user as platform rules. `algorithm` facts are signals, "
        "and `heuristic` facts are craft advice. If the preflight report lists a platform as stale, say so briefly and offer a refresh "
        "(see `spec-refresh.md`).",
        "",
        "Ranking signals are not recipes. Published weights multiply predicted probabilities, so they do not mean "
        "\"one reply equals N likes\". Never promise reach.",
        "",
    ]
    for pid, p in data["platforms"].items():
        lines += [f"## {p['label']} (`{pid}`)", ""]
        by_kind: dict[str, list[tuple[str, dict]]] = {}
        for key, fact in p["facts"].items():
            by_kind.setdefault(fact["kind"], []).append((key, fact))
        for kind in ("hard", "policy", "algorithm", "heuristic"):
            rows = by_kind.get(kind)
            if not rows:
                continue
            lines += [f"### {KIND_TITLES[kind]}", "", "| Fact | Value | Verified | Source | Note |", "|---|---|---|---|---|"]
            for key, f in rows:
                note = (f.get("note") or "").replace("|", "/")
                lines.append(f"| `{key}` | {fmt(f['value'])} | {f['verified_at']} | {SOURCE_LABEL.get(f['source_type'], f['source_type'])} | {note} |")
            lines.append("")
        official = list(p.get("primary_domains", [])) + list(p.get("primary_url_prefixes", []))
        if official:
            lines += ["Official sources for refreshes: " + ", ".join(f"`{o}`" for o in official), ""]
    lines += ["## Retired claims", "", "These circulate widely, including in earlier versions of this skill. They are wrong or unsupported. Do not repeat them.", ""]
    for c in data.get("retired_claims", []):
        lines.append(f"- {c['claim']}. {c['reason']}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = json.loads(SPECS.read_text(encoding="utf-8"))
    text = render(data)
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
